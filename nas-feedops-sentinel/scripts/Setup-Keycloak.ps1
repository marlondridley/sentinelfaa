# Setup-Keycloak.ps1
# Brings Keycloak up in production mode and creates an operator login.
#
#   1. .env      KEYCLOAK_DASHBOARD_CLIENT_SECRET is copied from
#                .streamlit/secrets.toml (the dashboard's side), so Keycloak
#                and the dashboard use one secret. If both exist and differ,
#                this stops rather than overwrite either.
#                KEYCLOAK_DB_PASSWORD is generated if absent.
#                Values are looked up in this stack's .env and then in
#                ../instraclustr/.env -- a secret may live in either, as the
#                launcher reads both; one found in either is not added again.
#   2. Keycloak  the local certificates are issued (edge-certs: tls/edge-ca.crt
#                and a certificate for Keycloak), then keycloak-postgres +
#                keycloak are started. Keycloak serves HTTPS only; the realm and
#                the dashboard client are imported from keycloak/realm-nas-sentinel.json.
#   3. Operator  one login in the nas-sentinel realm (you choose it now).
#
# This script talks to https://localhost:8081, so Windows must trust
# tls/edge-ca.crt (once, in Cert:\CurrentUser\Root). It checks, and tells you
# the one command to run if it is not trusted yet; it does not change your
# certificate store itself.
#
# -PrepareOnly runs step 1 only. Safe to re-run. Secrets are never printed
# and never placed on a command line.
[CmdletBinding()]
param([switch]$PrepareOnly)

$ErrorActionPreference = 'Stop'
$appDir      = Split-Path -Parent $PSScriptRoot
$envFile     = Join-Path $appDir '.env'
$infraEnv    = Join-Path (Join-Path (Split-Path -Parent $appDir) 'instraclustr') '.env'
$secretsFile = Join-Path (Join-Path $appDir '.streamlit') 'secrets.toml'
$composeFile = Join-Path $appDir 'docker-compose.yml'
$operatorSh  = Join-Path $PSScriptRoot 'keycloak-operator.sh'
$utf8NoBom   = New-Object System.Text.UTF8Encoding($false)

function Get-DotEnvValue([string]$Path, [string]$Key) {
    foreach ($line in [IO.File]::ReadAllLines($Path)) {
        if ($line -match "^\s*$([regex]::Escape($Key))\s*=\s*(.*)$") {
            return $Matches[1].Trim().Trim('"').Trim("'")
        }
    }
    return ''
}

# A value from this stack's .env, else from ../instraclustr/.env.
function Get-EnvValue([string]$Key) {
    $value = Get-DotEnvValue $envFile $Key
    if (-not $value -and (Test-Path $infraEnv)) { $value = Get-DotEnvValue $infraEnv $Key }
    return $value
}

# Both env files for docker compose, infrastructure first (as the launcher does).
$envArgs = @()
if (Test-Path $infraEnv) { $envArgs += @('--env-file', $infraEnv) }
$envArgs += @('--env-file', $envFile)

function Add-DotEnvValue([string]$Path, [string]$Key, [string]$Value, [string]$Comment) {
    $text = [IO.File]::ReadAllText($Path)
    $nl = if ($text.Contains("`r`n")) { "`r`n" } else { "`n" }
    $prefix = if ($text.Length -gt 0 -and -not $text.EndsWith("`n")) { $nl } else { '' }
    [IO.File]::AppendAllText($Path, "$prefix$nl# $Comment$nl$Key=$Value$nl", $utf8NoBom)
}

function Get-DashboardClientSecret([string]$Path) {
    $inSection = $false
    foreach ($line in [IO.File]::ReadAllLines($Path)) {
        if ($line -match '^\s*\[auth\.keycloak\]\s*$') { $inSection = $true; continue }
        if ($line -match '^\s*\[') { $inSection = $false }
        if ($inSection -and $line -match '^\s*client_secret\s*=\s*"?([^"]*)"?\s*$') { return $Matches[1].Trim() }
    }
    return ''
}

function New-RandomSecret([int]$Bytes = 32) {
    $buf = New-Object byte[] $Bytes
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($buf)
    return -join ($buf | ForEach-Object { $_.ToString('x2') })
}

# -- 1. .env ------------------------------------------------------------------
foreach ($f in $envFile, $secretsFile) { if (-not (Test-Path $f)) { throw "Missing $f" } }

$clientSecret = Get-DashboardClientSecret $secretsFile
if (-not $clientSecret -or $clientSecret -like 'REPLACE*') {
    throw "client_secret under [auth.keycloak] in $secretsFile is missing or still a placeholder."
}
$envSecret = Get-EnvValue 'KEYCLOAK_DASHBOARD_CLIENT_SECRET'
if (-not $envSecret) {
    Add-DotEnvValue $envFile 'KEYCLOAK_DASHBOARD_CLIENT_SECRET' $clientSecret 'Keycloak client secret for the dashboard; must equal client_secret in .streamlit/secrets.toml'
    Write-Host "  .env: KEYCLOAK_DASHBOARD_CLIENT_SECRET added (copied from secrets.toml)" -ForegroundColor Green
} elseif ($envSecret -ne $clientSecret) {
    throw ("KEYCLOAK_DASHBOARD_CLIENT_SECRET (in an env file) differs from client_secret in secrets.toml. " +
           "Decide which is correct, make the other match, and re-run. Nothing was changed.")
} else {
    Write-Host "  env: KEYCLOAK_DASHBOARD_CLIENT_SECRET matches secrets.toml" -ForegroundColor Green
}

if (-not (Get-EnvValue 'KEYCLOAK_DB_PASSWORD')) {
    Add-DotEnvValue $envFile 'KEYCLOAK_DB_PASSWORD' (New-RandomSecret) "Password for Keycloak's own Postgres (keycloak-postgres); generated by Setup-Keycloak.ps1"
    Write-Host "  .env: KEYCLOAK_DB_PASSWORD generated" -ForegroundColor Green
} else {
    Write-Host "  env: KEYCLOAK_DB_PASSWORD present" -ForegroundColor Green
}
$adminPw = Get-EnvValue 'KEYCLOAK_ADMIN_PASSWORD'
if (-not $adminPw) { throw "KEYCLOAK_ADMIN_PASSWORD is missing from $envFile and $infraEnv" }

if ($PrepareOnly) { Write-Host "Prepared .env (-PrepareOnly: Keycloak not started)."; return }

# -- 2. Keycloak --------------------------------------------------------------
Write-Host "Issuing local certificates (edge-certs)..." -ForegroundColor Yellow
docker compose -f $composeFile @envArgs up edge-certs
if ($LASTEXITCODE -ne 0) { throw "edge-certs could not issue the certificates (exit $LASTEXITCODE)." }
$caFile = Join-Path (Join-Path $appDir 'tls') 'edge-ca.crt'
if (-not (Test-Path $caFile)) { throw "Missing $caFile after edge-certs ran." }
$ca = New-Object Security.Cryptography.X509Certificates.X509Certificate2 $caFile
if (-not (Get-ChildItem Cert:\CurrentUser\Root | Where-Object Thumbprint -eq $ca.Thumbprint)) {
    throw ("Windows does not trust the local certificate authority yet, so https://localhost:8081 " +
           "cannot be verified. Trust it once, then re-run this script:`n" +
           "  Import-Certificate -FilePath `"$caFile`" -CertStoreLocation Cert:\CurrentUser\Root")
}

Write-Host "Starting keycloak-postgres and keycloak (production mode, HTTPS only)..." -ForegroundColor Yellow
docker compose -f $composeFile @envArgs up -d keycloak-postgres keycloak
if ($LASTEXITCODE -ne 0) { throw "docker compose could not start Keycloak (exit $LASTEXITCODE)." }

Write-Host "Waiting for the nas-sentinel realm (first start builds and imports; up to 3 minutes)..." -ForegroundColor Yellow
$ready = $false
for ($i = 0; $i -lt 90; $i++) {
    try { Invoke-WebRequest -UseBasicParsing -TimeoutSec 3 'https://localhost:8081/realms/nas-sentinel' | Out-Null; $ready = $true; break }
    catch { Start-Sleep -Seconds 2 }
}
if (-not $ready) { throw "Realm nas-sentinel did not come up on https://localhost:8081. Check: docker logs nas-keycloak --tail 50" }
Write-Host "  realm nas-sentinel is up (HTTPS, certificate verified)" -ForegroundColor Green

# -- 3. Operator login --------------------------------------------------------
$defaultUser = $env:USERNAME
$user  = Read-Host "Operator username [$defaultUser]"; if (-not $user) { $user = $defaultUser }
$email = Read-Host "Email for $user"
if ($email -notmatch '^[^@\s]+@[^@\s]+\.[^@\s]+$') { throw "That does not look like an email address." }
$pw1 = Read-Host "Password for $user (12+ characters, not the username or email)" -AsSecureString
$pw2 = Read-Host "Repeat password" -AsSecureString
$toPlain = { param($s) [Runtime.InteropServices.Marshal]::PtrToStringAuto([Runtime.InteropServices.Marshal]::SecureStringToBSTR($s)) }
$p1 = & $toPlain $pw1; $p2 = & $toPlain $pw2
if ($p1 -ne $p2) { throw "Passwords did not match." }
if ($p1.Length -lt 12) { throw "Use at least 12 characters (the realm's password policy)." }

$rbacSh = Join-Path $PSScriptRoot 'keycloak-rbac.sh'
docker cp $operatorSh nas-keycloak:/tmp/keycloak-operator.sh | Out-Null
docker cp $rbacSh nas-keycloak:/tmp/keycloak-rbac.sh | Out-Null
try {
    $env:KC_ADMIN_PW = $adminPw; $env:APP_USERNAME = $user; $env:APP_USER_PW = $p1; $env:APP_EMAIL = $email
    # The public sign-in callback as well, once public access is set up
    # (docs/public-access.md): without it this run would drop it from the
    # dashboard client, and sign-in through the public address would fail.
    $env:PUBLIC_DASHBOARD_URL = Get-EnvValue 'PUBLIC_DASHBOARD_URL'
    # Realm roles + ID-token mapper first: the operator script grants roles.
    docker exec -e KC_ADMIN_PW -e PUBLIC_DASHBOARD_URL nas-keycloak bash /tmp/keycloak-rbac.sh
    if ($LASTEXITCODE -ne 0) { throw "Applying realm roles failed inside the container (exit $LASTEXITCODE)." }
    # APP_ROLES defaults to watch_officer; set it before running this script
    # (e.g. $env:APP_ROLES = 'watch_officer,supervisor') to grant more.
    docker exec -e KC_ADMIN_PW -e APP_USERNAME -e APP_USER_PW -e APP_EMAIL -e APP_ROLES nas-keycloak bash /tmp/keycloak-operator.sh
    if ($LASTEXITCODE -ne 0) { throw "Creating the operator failed inside the container (exit $LASTEXITCODE)." }
}
finally {
    Remove-Item Env:KC_ADMIN_PW, Env:APP_USERNAME, Env:APP_USER_PW, Env:APP_EMAIL, Env:PUBLIC_DASHBOARD_URL -ErrorAction SilentlyContinue
    docker exec -u 0 nas-keycloak rm -f /tmp/keycloak-operator.sh /tmp/keycloak-rbac.sh | Out-Null   # docker cp: root-owned
}

# -- 4. Proof -----------------------------------------------------------------
$disc = Invoke-RestMethod 'https://localhost:8081/realms/nas-sentinel/.well-known/openid-configuration'
Write-Host ""
Write-Host "Keycloak is ready. The browser will be sent to:" -ForegroundColor Green
Write-Host "  issuer                 : $($disc.issuer)"
Write-Host "  authorization_endpoint : $($disc.authorization_endpoint)"
Write-Host ""
Write-Host "Next: docker compose --env-file .env up -d dashboard   (picks up the new settings)" -ForegroundColor Cyan
Write-Host "  .streamlit/secrets.toml must use server_metadata_url = https://keycloak:8443/... and" -ForegroundColor Cyan
Write-Host "  [auth.keycloak.client_kwargs] verify = /run/tls/edge-ca.crt (see .streamlit/secrets.toml.example)." -ForegroundColor Cyan
Write-Host "Then open https://localhost:8443 in a NEW tab and sign in as '$user'." -ForegroundColor Cyan
Write-Host "Keycloak admin console: https://localhost:8081/admin  (user 'admin', KEYCLOAK_ADMIN_PASSWORD)" -ForegroundColor DarkGray
